-- Adapter (mapping) views. The Budget module reads ERP master and JV data ONLY through these views.
-- Default: point at the isolated DM_* demo tables. For production, replace each FROM clause with the
-- real Ceevora table and column names (see docs/MAPPING_GUIDE.md). Column names and types on the
-- left of each AS must stay the same.

CREATE OR REPLACE VIEW BX_COMPANY AS
SELECT COMPANY_ID, COMPANY_CODE, COMPANY_NAME, COMPANY_NAME_AR, BASE_CURRENCY FROM DM_COMPANY;

CREATE OR REPLACE VIEW BX_BRANCH AS
SELECT BRANCH_ID, COMPANY_ID, BRANCH_CODE, BRANCH_NAME, BRANCH_NAME_AR, IS_ACTIVE FROM DM_BRANCH;

CREATE OR REPLACE VIEW BX_GL_ACCOUNT AS
SELECT GL_ACCOUNT_ID, COMPANY_ID, GL_CODE, GL_NAME, GL_NAME_AR, ACCOUNT_TYPE, BUDGET_CATEGORY,
       EXPENSE_GROUP, NORMAL_BALANCE, IS_POSTING, IS_ACTIVE, IS_VAT, IS_INTERNAL_TRANSFER
FROM DM_GL_ACCOUNT;

CREATE OR REPLACE VIEW BX_FIN_PERIOD AS
SELECT COMPANY_ID, FIN_YEAR, PERIOD_NO, PERIOD_NAME, START_DATE, END_DATE FROM DM_FIN_PERIOD;

-- JV_DATE is truncated so a time component can never push a voucher out of its period.
CREATE OR REPLACE VIEW BX_JV_HEADER AS
SELECT JV_ID, COMPANY_ID, BRANCH_ID, JV_NO, TRUNC(JV_DATE) AS JV_DATE, JV_TYPE, STATUS, DESCRIPTION FROM DM_JV_HEADER;

CREATE OR REPLACE VIEW BX_JV_DETAILS AS
SELECT JV_ID, LINE_NO, GL_ACCOUNT_ID, BRANCH_ID, DEBIT, CREDIT, NARRATION FROM DM_JV_DETAILS;

CREATE OR REPLACE VIEW BX_USERS AS
SELECT USER_ID, USERNAME, FULL_NAME, PASSWORD_HASH, ROLE_CODE, COMPANY_ID, ALL_BRANCHES, IS_ACTIVE FROM DM_USERS;

CREATE OR REPLACE VIEW BX_USER_BRANCH AS
SELECT USER_ID, BRANCH_ID FROM DM_USER_BRANCH;
