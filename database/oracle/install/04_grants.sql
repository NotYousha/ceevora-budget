-- Least-privilege runtime role for the API's connection user. Run as the schema owner.
-- The API must NOT connect as the schema owner. Create the app user separately (DBA task), e.g.
--   CREATE USER BUDGET_APP IDENTIFIED BY <secret from vault>; GRANT CREATE SESSION TO BUDGET_APP;
--   GRANT CEEVORA_BUDGET_APP TO BUDGET_APP; ALTER USER BUDGET_APP DEFAULT ROLE ALL;
-- then create private synonyms (or set CURRENT_SCHEMA in a logon trigger) for the objects below.
CREATE ROLE CEEVORA_BUDGET_APP;

GRANT SELECT, INSERT, UPDATE         ON BUDGET_MASTER           TO CEEVORA_BUDGET_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BUDGET_DETAILS          TO CEEVORA_BUDGET_APP;
GRANT SELECT, INSERT                 ON BUDGET_APPROVAL_HISTORY TO CEEVORA_BUDGET_APP;
GRANT SELECT, INSERT, UPDATE         ON BUDGET_REVISION_HISTORY TO CEEVORA_BUDGET_APP;
GRANT SELECT, INSERT, DELETE         ON BUDGET_ROLE_PERMISSION  TO CEEVORA_BUDGET_APP;
GRANT SELECT, INSERT, UPDATE         ON BUDGET_SETTINGS         TO CEEVORA_BUDGET_APP;
GRANT SELECT, INSERT                 ON BUDGET_IDEMPOTENCY      TO CEEVORA_BUDGET_APP;

GRANT SELECT ON BX_COMPANY        TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_BRANCH         TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_GL_ACCOUNT     TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_FIN_PERIOD     TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_JV_HEADER      TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_JV_DETAILS     TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_USERS          TO CEEVORA_BUDGET_APP;
GRANT SELECT ON BX_USER_BRANCH    TO CEEVORA_BUDGET_APP;
GRANT SELECT ON V_BUDGET_APPROVED TO CEEVORA_BUDGET_APP;
GRANT SELECT ON V_BUDGET_ACTUAL   TO CEEVORA_BUDGET_APP;
GRANT SELECT ON V_BUDGET_VARIANCE TO CEEVORA_BUDGET_APP;
