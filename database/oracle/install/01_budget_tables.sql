-- Ceevora ERP - Budget Module - core tables (Oracle 19c / 26ai)
-- Run as the tenant schema owner inside the customer PDB.
-- Production table names for Company/Branch/COA/JV/User were NOT supplied; the module reads
-- them only through the BX_* adapter views (02_adapter_views.sql). See docs/MAPPING_GUIDE.md.

CREATE TABLE BUDGET_MASTER (
  BUDGET_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COMPANY_ID         NUMBER        NOT NULL,
  BUDGET_NO          VARCHAR2(30)  NOT NULL,
  BUDGET_NAME        VARCHAR2(200) NOT NULL,
  BUDGET_TYPE        VARCHAR2(20)  DEFAULT 'OPERATING' NOT NULL,
  FIN_YEAR           NUMBER(4)     NOT NULL,
  START_DATE         DATE          NOT NULL,
  END_DATE           DATE          NOT NULL,
  CURRENCY_CODE      VARCHAR2(3)   NOT NULL,
  ALLOCATION_METHOD  VARCHAR2(20)  DEFAULT 'CALENDAR_DAYS' NOT NULL,
  STATUS             VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
  VERSION_NO         NUMBER(6)     DEFAULT 0 NOT NULL,
  REMARKS            VARCHAR2(1000),
  ROW_VERSION        NUMBER(10)    DEFAULT 1 NOT NULL,
  SUBMITTED_BY       VARCHAR2(50),
  SUBMITTED_AT       TIMESTAMP,
  APPROVED_BY        VARCHAR2(50),
  APPROVED_AT        TIMESTAMP,
  CREATED_BY         VARCHAR2(50)  NOT NULL,
  CREATED_AT         TIMESTAMP     NOT NULL,
  UPDATED_BY         VARCHAR2(50),
  UPDATED_AT         TIMESTAMP,
  CONSTRAINT BM_TYPE_CK   CHECK (BUDGET_TYPE IN ('OPERATING')),
  CONSTRAINT BM_STATUS_CK CHECK (STATUS IN ('DRAFT','SUBMITTED','APPROVED')),
  CONSTRAINT BM_ALLOC_CK  CHECK (ALLOCATION_METHOD IN ('CALENDAR_DAYS','WORKING_DAYS')),
  CONSTRAINT BM_DATES_CK  CHECK (END_DATE > START_DATE),
  CONSTRAINT BM_NO_UK     UNIQUE (COMPANY_ID, BUDGET_NO),
  CONSTRAINT BM_ANNUAL_UK UNIQUE (COMPANY_ID, FIN_YEAR, BUDGET_TYPE)
);
COMMENT ON TABLE  BUDGET_MASTER IS 'Budget header. One operating budget per company and financial year.';
COMMENT ON COLUMN BUDGET_MASTER.VERSION_NO  IS '0 = never approved; 1 = initial approval; +1 per approved revision batch.';
COMMENT ON COLUMN BUDGET_MASTER.ROW_VERSION IS 'Optimistic concurrency token; incremented on every update.';

CREATE TABLE BUDGET_DETAILS (
  DETAIL_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BUDGET_ID          NUMBER        NOT NULL,
  BRANCH_ID          NUMBER        NOT NULL,
  GL_ACCOUNT_ID      NUMBER        NOT NULL,
  PERIOD_NO          NUMBER(2)     NOT NULL,
  ORIGINAL_AMOUNT    NUMBER(18,2),
  CURRENT_AMOUNT     NUMBER(18,2)  DEFAULT 0 NOT NULL,
  ROW_VERSION        NUMBER(10)    DEFAULT 1 NOT NULL,
  CREATED_BY         VARCHAR2(50)  NOT NULL,
  CREATED_AT         TIMESTAMP     NOT NULL,
  UPDATED_BY         VARCHAR2(50),
  UPDATED_AT         TIMESTAMP,
  CONSTRAINT BD_BUDGET_FK FOREIGN KEY (BUDGET_ID) REFERENCES BUDGET_MASTER (BUDGET_ID),
  CONSTRAINT BD_PERIOD_CK CHECK (PERIOD_NO BETWEEN 1 AND 13),
  CONSTRAINT BD_LINE_UK   UNIQUE (BUDGET_ID, BRANCH_ID, GL_ACCOUNT_ID, PERIOD_NO)
);
COMMENT ON TABLE  BUDGET_DETAILS IS 'Monthly budget amount per branch, GL account and period.';
COMMENT ON COLUMN BUDGET_DETAILS.ORIGINAL_AMOUNT IS 'Frozen at initial approval (version 1); never changed afterwards.';
COMMENT ON COLUMN BUDGET_DETAILS.CURRENT_AMOUNT  IS 'Active amount. Changes only through draft entry or approved revisions.';

CREATE TABLE BUDGET_APPROVAL_HISTORY (
  HISTORY_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BUDGET_ID          NUMBER        NOT NULL,
  ACTION             VARCHAR2(30)  NOT NULL,
  PREVIOUS_STATUS    VARCHAR2(20),
  NEW_STATUS         VARCHAR2(20)  NOT NULL,
  VERSION_NO         NUMBER(6)     NOT NULL,
  ACTION_BY          VARCHAR2(50)  NOT NULL,
  ACTION_AT          TIMESTAMP     NOT NULL,
  REMARKS            VARCHAR2(1000),
  REJECTION_REASON   VARCHAR2(1000),
  CONSTRAINT BAH_BUDGET_FK FOREIGN KEY (BUDGET_ID) REFERENCES BUDGET_MASTER (BUDGET_ID),
  CONSTRAINT BAH_ACTION_CK CHECK (ACTION IN ('CREATE','UPDATE','SUBMIT','APPROVE','REJECT','REVISION_APPROVED','REVISION_REJECTED'))
);
COMMENT ON TABLE BUDGET_APPROVAL_HISTORY IS 'System-generated, immutable workflow audit (insert-only).';

CREATE TABLE BUDGET_REVISION_HISTORY (
  REVISION_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BUDGET_ID                NUMBER        NOT NULL,
  DETAIL_ID                NUMBER        NOT NULL,
  BRANCH_ID                NUMBER        NOT NULL,
  GL_ACCOUNT_ID            NUMBER        NOT NULL,
  PERIOD_NO                NUMBER(2)     NOT NULL,
  BASE_VERSION_NO          NUMBER(6)     NOT NULL,
  VERSION_NO               NUMBER(6),
  ORIGINAL_AMOUNT          NUMBER(18,2)  NOT NULL,
  PREVIOUS_APPROVED_AMOUNT NUMBER(18,2)  NOT NULL,
  REVISED_AMOUNT           NUMBER(18,2)  NOT NULL,
  DIFFERENCE_AMOUNT        NUMBER(18,2)  NOT NULL,
  DIFFERENCE_PCT           NUMBER(12,4),
  DETAIL_ROW_VERSION       NUMBER(10)    NOT NULL,
  STATUS                   VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL,
  REASON                   VARCHAR2(1000) NOT NULL,
  REJECTION_REASON         VARCHAR2(1000),
  REVISED_BY               VARCHAR2(50)  NOT NULL,
  REVISED_AT               TIMESTAMP     NOT NULL,
  APPROVED_BY              VARCHAR2(50),
  APPROVED_AT              TIMESTAMP,
  CONSTRAINT BRH_BUDGET_FK FOREIGN KEY (BUDGET_ID) REFERENCES BUDGET_MASTER (BUDGET_ID),
  CONSTRAINT BRH_DETAIL_FK FOREIGN KEY (DETAIL_ID) REFERENCES BUDGET_DETAILS (DETAIL_ID),
  CONSTRAINT BRH_STATUS_CK CHECK (STATUS IN ('PENDING','APPROVED','REJECTED'))
);
COMMENT ON TABLE  BUDGET_REVISION_HISTORY IS 'Line revisions. PENDING -> APPROVED | REJECTED. Only APPROVED rows change BUDGET_DETAILS.CURRENT_AMOUNT.';
COMMENT ON COLUMN BUDGET_REVISION_HISTORY.DETAIL_ROW_VERSION IS 'BUDGET_DETAILS.ROW_VERSION when requested; approval is refused if it changed (stale).';
COMMENT ON COLUMN BUDGET_REVISION_HISTORY.DIFFERENCE_PCT IS 'NULL means N/A (previous approved amount was zero).';

CREATE TABLE BUDGET_ROLE_PERMISSION (
  ROLE_CODE        VARCHAR2(30) NOT NULL,
  PERMISSION_CODE  VARCHAR2(50) NOT NULL,
  CONSTRAINT BRP_PK PRIMARY KEY (ROLE_CODE, PERMISSION_CODE)
);

CREATE TABLE BUDGET_SETTINGS (
  SETTING_KEY    VARCHAR2(50)  PRIMARY KEY,
  SETTING_VALUE  VARCHAR2(200) NOT NULL
);

CREATE TABLE BUDGET_IDEMPOTENCY (
  IDEM_KEY       VARCHAR2(100) PRIMARY KEY,
  USER_NAME      VARCHAR2(50)  NOT NULL,
  ENDPOINT       VARCHAR2(200) NOT NULL,
  RESPONSE_JSON  CLOB,
  CREATED_AT     TIMESTAMP     NOT NULL
);
COMMENT ON TABLE BUDGET_IDEMPOTENCY IS 'Replay cache for write requests carrying an Idempotency-Key header. Purge rows older than 7 days.';

CREATE INDEX BD_BRANCH_IX    ON BUDGET_DETAILS (BRANCH_ID, GL_ACCOUNT_ID);
CREATE INDEX BAH_BUDGET_IX   ON BUDGET_APPROVAL_HISTORY (BUDGET_ID, ACTION_AT);
CREATE INDEX BRH_BUDGET_IX   ON BUDGET_REVISION_HISTORY (BUDGET_ID, STATUS);
CREATE INDEX BRH_DETAIL_IX   ON BUDGET_REVISION_HISTORY (DETAIL_ID);
CREATE INDEX BM_COMPANY_IX   ON BUDGET_MASTER (COMPANY_ID, STATUS);

-- Audit immutability: approval history is insert-only; revision history rows may only move out of PENDING once.
CREATE OR REPLACE TRIGGER BAH_IMMUTABLE_TRG
BEFORE UPDATE OR DELETE ON BUDGET_APPROVAL_HISTORY
BEGIN
  RAISE_APPLICATION_ERROR(-20901, 'BUDGET_APPROVAL_HISTORY is immutable');
END;
/

CREATE OR REPLACE TRIGGER BRH_IMMUTABLE_TRG
BEFORE UPDATE OR DELETE ON BUDGET_REVISION_HISTORY
FOR EACH ROW
BEGIN
  IF DELETING OR :OLD.STATUS <> 'PENDING'
     OR :NEW.REVISED_AMOUNT <> :OLD.REVISED_AMOUNT
     OR :NEW.PREVIOUS_APPROVED_AMOUNT <> :OLD.PREVIOUS_APPROVED_AMOUNT
     OR :NEW.REVISED_BY <> :OLD.REVISED_BY THEN
    RAISE_APPLICATION_ERROR(-20902, 'BUDGET_REVISION_HISTORY row is immutable');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER BD_ORIGINAL_TRG
BEFORE UPDATE OF ORIGINAL_AMOUNT ON BUDGET_DETAILS
FOR EACH ROW
WHEN (OLD.ORIGINAL_AMOUNT IS NOT NULL)
BEGIN
  RAISE_APPLICATION_ERROR(-20903, 'ORIGINAL_AMOUNT is frozen after initial approval');
END;
/
