-- Post-install checks. Each query states its expected result.
SET PAGESIZE 100 LINESIZE 200
PROMPT Invalid budget objects (expected: no rows)
SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS
 WHERE STATUS <> 'VALID'
   AND (OBJECT_NAME LIKE 'BUDGET%' OR OBJECT_NAME LIKE 'BX%' OR OBJECT_NAME LIKE 'V_BUDGET%'
        OR OBJECT_NAME IN ('BAH_IMMUTABLE_TRG','BRH_IMMUTABLE_TRG','BD_ORIGINAL_TRG'));

PROMPT Required tables and views present (expected: 18)
SELECT COUNT(*) AS PRESENT FROM USER_OBJECTS WHERE OBJECT_TYPE IN ('TABLE','VIEW') AND OBJECT_NAME IN (
 'BUDGET_MASTER','BUDGET_DETAILS','BUDGET_APPROVAL_HISTORY','BUDGET_REVISION_HISTORY','BUDGET_ROLE_PERMISSION',
 'BUDGET_SETTINGS','BUDGET_IDEMPOTENCY','BX_COMPANY','BX_BRANCH','BX_GL_ACCOUNT','BX_FIN_PERIOD','BX_JV_HEADER',
 'BX_JV_DETAILS','BX_USERS','BX_USER_BRANCH','V_BUDGET_APPROVED','V_BUDGET_ACTUAL','V_BUDGET_VARIANCE');

PROMPT Duplicate budget lines (expected: no rows)
SELECT BUDGET_ID, BRANCH_ID, GL_ACCOUNT_ID, PERIOD_NO, COUNT(*) AS N FROM BUDGET_DETAILS
 GROUP BY BUDGET_ID, BRANCH_ID, GL_ACCOUNT_ID, PERIOD_NO HAVING COUNT(*) > 1;

PROMPT Approved budgets with unfrozen original amounts (expected: no rows)
SELECT d.DETAIL_ID FROM BUDGET_DETAILS d JOIN BUDGET_MASTER m ON m.BUDGET_ID = d.BUDGET_ID
 WHERE m.STATUS = 'APPROVED' AND d.ORIGINAL_AMOUNT IS NULL;

PROMPT Posted JVs outside any financial period (expected: no rows; they would be missing from actuals)
SELECT h.JV_ID, h.JV_DATE FROM BX_JV_HEADER h WHERE h.STATUS = 'POSTED' AND NOT EXISTS (
 SELECT 1 FROM BX_FIN_PERIOD p WHERE p.COMPANY_ID = h.COMPANY_ID AND h.JV_DATE BETWEEN p.START_DATE AND p.END_DATE);

PROMPT Overlapping financial periods (expected: no rows; overlaps would double-count actuals)
SELECT a.COMPANY_ID, a.FIN_YEAR, a.PERIOD_NO, b.FIN_YEAR AS FIN_YEAR_2, b.PERIOD_NO AS PERIOD_NO_2
  FROM BX_FIN_PERIOD a JOIN BX_FIN_PERIOD b ON a.COMPANY_ID = b.COMPANY_ID
   AND (a.FIN_YEAR < b.FIN_YEAR OR (a.FIN_YEAR = b.FIN_YEAR AND a.PERIOD_NO < b.PERIOD_NO))
   AND a.START_DATE <= b.END_DATE AND b.START_DATE <= a.END_DATE;

PROMPT Budget categories on non-P&L accounts (expected: no rows)
SELECT GL_CODE FROM BX_GL_ACCOUNT WHERE BUDGET_CATEGORY IS NOT NULL AND ACCOUNT_TYPE NOT IN ('REVENUE','EXPENSE');
