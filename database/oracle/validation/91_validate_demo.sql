PROMPT Demo Jan 2027 net sales budget / actual (expected 1: 200000/185000, 2: 150000/165000, 3: 100000/90000)
SELECT BRANCH_ID,
       SUM(CASE WHEN BUDGET_CATEGORY = 'SALES' THEN BUDGET_AMOUNT ELSE -BUDGET_AMOUNT END) AS NET_BUDGET,
       SUM(CASE WHEN BUDGET_CATEGORY = 'SALES' THEN ACTUAL_AMOUNT ELSE -ACTUAL_AMOUNT END) AS NET_ACTUAL
  FROM V_BUDGET_VARIANCE
 WHERE FIN_YEAR = 2027 AND PERIOD_NO = 1 AND BUDGET_CATEGORY IN ('SALES','DISCOUNT','RETURN')
 GROUP BY BRANCH_ID ORDER BY BRANCH_ID;

PROMPT Unbudgeted actuals (expected: one row, GL 6400, branch 1, 1500)
