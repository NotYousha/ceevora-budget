-- DEMO ONLY: isolated stand-ins for Ceevora Company / Branch / COA / Financial Period / JV / User tables.
-- Do NOT run in production. In production, point the BX_* adapter views at the real ERP tables instead.

CREATE TABLE DM_COMPANY (
  COMPANY_ID      NUMBER PRIMARY KEY,
  COMPANY_CODE    VARCHAR2(20)  NOT NULL UNIQUE,
  COMPANY_NAME    VARCHAR2(200) NOT NULL,
  COMPANY_NAME_AR VARCHAR2(200),
  BASE_CURRENCY   VARCHAR2(3)   NOT NULL
);

CREATE TABLE DM_BRANCH (
  BRANCH_ID      NUMBER PRIMARY KEY,
  COMPANY_ID     NUMBER        NOT NULL REFERENCES DM_COMPANY (COMPANY_ID),
  BRANCH_CODE    VARCHAR2(20)  NOT NULL,
  BRANCH_NAME    VARCHAR2(200) NOT NULL,
  BRANCH_NAME_AR VARCHAR2(200),
  IS_ACTIVE      CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CONSTRAINT DM_BRANCH_UK UNIQUE (COMPANY_ID, BRANCH_CODE)
);

CREATE TABLE DM_GL_ACCOUNT (
  GL_ACCOUNT_ID        NUMBER PRIMARY KEY,
  COMPANY_ID           NUMBER        NOT NULL REFERENCES DM_COMPANY (COMPANY_ID),
  GL_CODE              VARCHAR2(30)  NOT NULL,
  GL_NAME              VARCHAR2(200) NOT NULL,
  GL_NAME_AR           VARCHAR2(200),
  ACCOUNT_TYPE         VARCHAR2(20)  NOT NULL CHECK (ACCOUNT_TYPE IN ('ASSET','LIABILITY','EQUITY','REVENUE','EXPENSE')),
  BUDGET_CATEGORY      VARCHAR2(20)  CHECK (BUDGET_CATEGORY IN ('SALES','DISCOUNT','RETURN','COGS','OPEX')),
  EXPENSE_GROUP        VARCHAR2(50),
  NORMAL_BALANCE       CHAR(1)       NOT NULL CHECK (NORMAL_BALANCE IN ('D','C')),
  IS_POSTING           CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_POSTING IN ('Y','N')),
  IS_ACTIVE            CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  IS_VAT               CHAR(1) DEFAULT 'N' NOT NULL CHECK (IS_VAT IN ('Y','N')),
  IS_INTERNAL_TRANSFER CHAR(1) DEFAULT 'N' NOT NULL CHECK (IS_INTERNAL_TRANSFER IN ('Y','N')),
  CONSTRAINT DM_GL_UK UNIQUE (COMPANY_ID, GL_CODE)
);

CREATE TABLE DM_FIN_PERIOD (
  COMPANY_ID   NUMBER       NOT NULL REFERENCES DM_COMPANY (COMPANY_ID),
  FIN_YEAR     NUMBER(4)    NOT NULL,
  PERIOD_NO    NUMBER(2)    NOT NULL,
  PERIOD_NAME  VARCHAR2(30) NOT NULL,
  START_DATE   DATE         NOT NULL,
  END_DATE     DATE         NOT NULL,
  CONSTRAINT DM_FIN_PERIOD_PK PRIMARY KEY (COMPANY_ID, FIN_YEAR, PERIOD_NO)
);

CREATE TABLE DM_JV_HEADER (
  JV_ID        NUMBER PRIMARY KEY,
  COMPANY_ID   NUMBER       NOT NULL REFERENCES DM_COMPANY (COMPANY_ID),
  BRANCH_ID    NUMBER       NOT NULL REFERENCES DM_BRANCH (BRANCH_ID),
  JV_NO        VARCHAR2(30) NOT NULL,
  JV_DATE      DATE         NOT NULL,
  JV_TYPE      VARCHAR2(30) NOT NULL,
  STATUS       VARCHAR2(20) NOT NULL CHECK (STATUS IN ('DRAFT','POSTED','REVERSED')),
  DESCRIPTION  VARCHAR2(400)
);
CREATE INDEX DM_JVH_DATE_IX ON DM_JV_HEADER (COMPANY_ID, JV_DATE, STATUS);

CREATE TABLE DM_JV_DETAILS (
  JV_ID          NUMBER       NOT NULL REFERENCES DM_JV_HEADER (JV_ID),
  LINE_NO        NUMBER(5)    NOT NULL,
  GL_ACCOUNT_ID  NUMBER       NOT NULL REFERENCES DM_GL_ACCOUNT (GL_ACCOUNT_ID),
  BRANCH_ID      NUMBER,
  DEBIT          NUMBER(18,2) DEFAULT 0 NOT NULL,
  CREDIT         NUMBER(18,2) DEFAULT 0 NOT NULL,
  NARRATION      VARCHAR2(400),
  CONSTRAINT DM_JVD_PK PRIMARY KEY (JV_ID, LINE_NO)
);
CREATE INDEX DM_JVD_GL_IX ON DM_JV_DETAILS (GL_ACCOUNT_ID);

CREATE TABLE DM_USERS (
  USER_ID        NUMBER PRIMARY KEY,
  USERNAME       VARCHAR2(50)  NOT NULL UNIQUE,
  FULL_NAME      VARCHAR2(200) NOT NULL,
  PASSWORD_HASH  VARCHAR2(200) NOT NULL,
  ROLE_CODE      VARCHAR2(30)  NOT NULL,
  COMPANY_ID     NUMBER        NOT NULL REFERENCES DM_COMPANY (COMPANY_ID),
  ALL_BRANCHES   CHAR(1) DEFAULT 'N' NOT NULL CHECK (ALL_BRANCHES IN ('Y','N')),
  IS_ACTIVE      CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE DM_USER_BRANCH (
  USER_ID    NUMBER NOT NULL REFERENCES DM_USERS (USER_ID),
  BRANCH_ID  NUMBER NOT NULL REFERENCES DM_BRANCH (BRANCH_ID),
  CONSTRAINT DM_USER_BRANCH_PK PRIMARY KEY (USER_ID, BRANCH_ID)
);
